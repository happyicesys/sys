    public function run(): void
    {
        foreach (self::BATCHES as $telcoName => $iccids) {
            $telco = Telco::where('name', $telcoName)->first();

            if (! $telco) {
                throw new \RuntimeException(
                    'Telco "'.$telcoName.'" not found — create the SimCard Package first.'
                );
            }

            $existing = Simcard::whereIn('code', $iccids)->pluck('code')->all();
            $created = 0;

            foreach ($iccids as $iccid) {
                if (in_array($iccid, $existing, true)) {
                    continue;
                }

                Simcard::create([
                    'code' => $iccid,
                    'telco_id' => $telco->id,
                    'is_active' => true,
                    'created_by' => self::CREATED_BY,
                ]);
                $created++;
            }

            $this->command?->info(
                "{$telcoName} sims: {$created} created, ".count($existing).' already present (telco #'.$telco->id.').'
            );
        }
    }
