        $telco = Telco::where('name', 'like', self::TELCO_NAME_PREFIX.'%')->first();

        if (! $telco) {
            throw new \RuntimeException(
                'Telco "'.self::TELCO_NAME_PREFIX.'..." not found — create the SimCard Package first.'
            );
        }

        $existing = Simcard::whereIn('code', self::ICCIDS)->pluck('code')->all();
        $created = 0;

        foreach (array_unique(self::ICCIDS) as $iccid) {
            if (in_array($iccid, $existing, true)) {
                continue;
            }

            Simcard::create([
                'code' => $iccid,
                'telco_id' => $telco->id,
                'is_active' => true,
                'created_by' => self::CREATED_BY,
            ]);
            $created++;
        }

        $this->command?->info(
            "VoicePing 6GB sims: {$created} created, ".count($existing).' already present (telco #'.$telco->id." {$telco->name})."
        );
    }
