    public function run(): void
    {
        $telco = Telco::where('name', self::TELCO_NAME)->first()
            ?? Telco::where('name', 'LIKE', '%Singtel 800MB%')->first();

        if (! $telco) {
            throw new \RuntimeException(
                'Telco "'.self::TELCO_NAME.'" not found — create the SimCard Package first.'
            );
        }

        $existing = Simcard::whereIn('code', self::ICCIDS)->pluck('code')->all();
        $created = 0;

        foreach (array_unique(self::ICCIDS) as $iccid) {
            if (in_array($iccid, $existing, true)) {
                continue;
            }

            Simcard::create([
                'code' => $iccid,
                'telco_id' => $telco->id,
                'is_active' => true,
                'created_by' => self::CREATED_BY,
            ]);
            $created++;
        }

        $this->command?->info(
            "VP-Singtel 800MB sims: {$created} created, ".count($existing).' already present (telco #'.$telco->id." {$telco->name})."
        );
    }
